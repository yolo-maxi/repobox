#!/usr/bin/env python3
"""Create the shared edge secret for an app-resolver primary host (Kodu mode).

usage: primary-host-edge-secret.py HOST [--rotate] [--root DIR]

Writes, as root:
  /etc/caddy/repobox-platform/secrets/HOST.edge.caddy   0640 root:caddy  `header_up X-Kodu-Edge "<secret>"`
  /etc/repobox-platform/HOST.edge-secret                0600 root:root   the raw secret, for the app operator to
                                                                          place in the app's own config
Refuses to overwrite unless --rotate (then the app config must be updated in the same change window).
Prints paths only, never the secret. --root DIR puts both files under DIR (tests).
"""
import argparse, grp, os, re, secrets, sys

ap = argparse.ArgumentParser()
ap.add_argument("host"); ap.add_argument("--rotate", action="store_true"); ap.add_argument("--root", default="")
a = ap.parse_args()
if not re.fullmatch(r"[a-z0-9-]+(\.[a-z0-9-]+){1,3}", a.host):
    sys.exit("refused: host must be a lowercase DNS name")
snippet = f"{a.root}/etc/caddy/repobox-platform/secrets/{a.host}.edge.caddy"
raw = f"{a.root}/etc/repobox-platform/{a.host}.edge-secret"
if not a.rotate and (os.path.exists(snippet) or os.path.exists(raw)):
    sys.exit("refused: secret exists (use --rotate in a coordinated change window)")
value = secrets.token_hex(32)
for path, mode, body in ((raw, 0o600, value + "\n"), (snippet, 0o640, f'# GENERATED by primary-host-edge-secret.py. Do not edit or print.\nheader_up X-Kodu-Edge "{value}"\n')):
    os.makedirs(os.path.dirname(path), mode=0o750, exist_ok=True)
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, mode)
    with os.fdopen(fd, "w") as f:
        f.write(body)
    if not a.root and path == snippet:
        os.chown(tmp, 0, grp.getgrnam("caddy").gr_gid)
    os.replace(tmp, path)
print(f"wrote {snippet} (0640) and {raw} (0600); validate + reload Caddy, then configure the app with the same value")
