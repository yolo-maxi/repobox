#!/usr/bin/env python3
"""Turn a landing build's headers file into the Caddy snippet a primary host imports.

usage: landing-headers.py BUILD_HEADERS_JSON OUT_CADDY

BUILD_HEADERS_JSON is the landing build's `dist-landing.headers.json`
({"headers": {name: value}, "cache": {...}}). Only known response headers are
accepted, values may not contain quotes, braces, backslashes or control
characters (they are written verbatim into the Caddyfile), and the CSP must
deny framing. The snippet is imported by `repobox-platform routes render`
output at /srv/<host>/headers.caddy; install it as root, then validate + reload.
"""
import json, re, sys

ALLOWED = {
    "Content-Security-Policy", "Referrer-Policy", "X-Content-Type-Options", "Permissions-Policy",
    "Cross-Origin-Opener-Policy", "Cross-Origin-Resource-Policy", "Strict-Transport-Security",
}
SAFE = re.compile(r"^[A-Za-z0-9 '\-_.,;:=/()+*@%]*$")
IMMUTABLE = "public, max-age=31536000, immutable"
REVALIDATE = "public, max-age=0, must-revalidate"


def main(src, out):
    data = json.load(open(src))
    headers = data.get("headers") or {}
    if not headers or set(headers) - ALLOWED:
        sys.exit(f"refused: unknown or missing headers {sorted(set(headers) - ALLOWED)}")
    for k, v in headers.items():
        if not isinstance(v, str) or not v or not SAFE.match(v):
            sys.exit(f"refused: unsafe value for {k}")
    csp = headers.get("Content-Security-Policy", "")
    if "frame-ancestors 'none'" not in csp or "default-src 'none'" not in csp:
        sys.exit("refused: CSP must keep default-src 'none' and frame-ancestors 'none'")
    cache = data.get("cache") or {}
    if cache.get("/_landing/assets/*") != IMMUTABLE:
        sys.exit("refused: unexpected cache rule for /_landing/assets/*")
    lines = ["# GENERATED by landing-headers.py from the landing build's headers file. Do not edit by hand.", "header {"]
    lines += [f'\t{k} "{v}"' for k, v in sorted(headers.items())]
    lines += ["\t-Server", "}", f'header ?Cache-Control "{REVALIDATE}"', f'header /_landing/assets/* Cache-Control "{IMMUTABLE}"', ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}: {len(headers)} headers")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
